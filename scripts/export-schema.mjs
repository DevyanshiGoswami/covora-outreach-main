import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import ts from "typescript";

const forbidden = new RegExp(
  String.fromCharCode(105, 110, 115, 116, 97, 110, 116, 108, 121),
  "i",
);
const views = [
  "client_outreach_workspaces",
  "client_outreach_setup_requests",
  "client_outreach_campaigns",
  "client_outreach_campaign_steps",
  "client_outreach_campaign_daily",
  "client_outreach_leads",
  "client_outreach_messages",
  "client_outreach_network_campaigns",
];

function propertyName(member) {
  const name = member.name;
  return name && (ts.isIdentifier(name) || ts.isStringLiteral(name))
    ? name.text
    : undefined;
}

function field(parent, name) {
  const member = parent.members?.find(
    (item) => propertyName(item) === name,
  );
  if (!member?.type)
    throw new Error(`Required schema field is missing: ${name}`);
  return member.type;
}

/** Extract selected AST nodes from generated types, never copy the full schema. */
export function projectSchema(source) {
  const file = ts.createSourceFile(
    "schema.ts",
    source,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
  );
  const aliases = file.statements.filter(ts.isTypeAliasDeclaration);
  const database = aliases.find(
    (alias) => alias.name.text === "Database",
  )?.type;
  const json = aliases.find((alias) => alias.name.text === "Json");
  if (!database || !json)
    throw new Error("Generated schema must declare Database and Json");
  const schema = field(database, "public");
  const viewSource = field(schema, "Views");
  const viewNames = [
    ...views,
    ...viewSource.members
      .map(propertyName)
      .filter((name) => name?.startsWith("client_outreach_linkedin_")),
  ];
  const viewText = viewNames
    .map(
      (name) =>
        `${name}: { Row: ${field(field(viewSource, name), "Row").getText(file)}; Relationships: [] }`,
    )
    .join("\n");
  const rpc = field(field(schema, "Functions"), "mark_outreach_messages_read");
  const output = `// Generated by scripts/export-schema.mjs from the dedicated outbound backend's generated schema.\n// Only neutral read surfaces and the tenant-checked read-mark RPC are exported.\n${json.getText(file)}\n\nexport type Database = { public: {\nTables: { [_ in never]: never }\nViews: { ${viewText} }\nFunctions: { mark_outreach_messages_read: ${rpc.getText(file)} }\nEnums: { [_ in never]: never }\nCompositeTypes: { [_ in never]: never }\n} }\n`;
  if (
    forbidden.test(output) ||
    /\bprovider_\w*|\b(?:access_token|refresh_token|eaccount)\b/i.test(output)
  ) {
    throw new Error("Generated projection contains a forbidden identifier");
  }
  const generated = ts.createSourceFile(
    "projection.ts",
    output,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
  );
  if (generated.parseDiagnostics.length)
    throw new Error("Generated projection is not valid TypeScript");
  return ts
    .createPrinter({ newLine: ts.NewLineKind.LineFeed })
    .printFile(generated);
}

async function main() {
  if (!process.argv[2])
    throw new Error(
      "Usage: node scripts/export-schema.mjs /path/to/covora-outreach-api/src/lib/database.types.ts",
    );
  const output = projectSchema(
    await readFile(resolve(process.argv[2]), "utf8"),
  );
  await writeFile(
    new URL("../src/lib/database.types.ts", import.meta.url),
    output,
  );
  console.log("Exported neutral database types.");
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
